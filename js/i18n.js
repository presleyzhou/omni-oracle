const OO_LANGS = [
  ["en", "English"],
  ["zh", "中文"],
  ["fr", "Français"],
  ["es", "Español"],
  ["ko", "한국어"],
];

let OO_LANG = localStorage.getItem("oo-lang") || "en";
if (!OO_LANGS.some(([v]) => v === OO_LANG)) OO_LANG = "en";

function OO_T(key) {
  return (I18N[OO_LANG] && I18N[OO_LANG][key]) || I18N.en[key] || key;
}

function applyI18n() {
  document.documentElement.lang = OO_LANG === "zh" ? "zh-CN" : OO_LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.innerHTML = OO_T(el.dataset.i18n);
  });
  document.dispatchEvent(new CustomEvent("oo:lang"));
}

/* dictionary loader: localStorage cache (keyed by asset version) → network */
const dictKey = (lang) => "oo-dict-" + lang;
function loadCachedDict(lang) {
  try {
    const c = JSON.parse(localStorage.getItem(dictKey(lang)));
    if (c && c.v === OO_VER && c.d) { I18N[lang] = c.d; return true; }
  } catch (e) {}
  return false;
}
async function loadLang(lang) {
  if (I18N[lang] || loadCachedDict(lang)) return true;
  try {
    const res = await fetch(`i18n/${lang}.json?v=${OO_VER}`);
    if (!res.ok) throw new Error(res.status);
    I18N[lang] = await res.json();
    try { localStorage.setItem(dictKey(lang), JSON.stringify({ v: OO_VER, d: I18N[lang] })); } catch (e) {}
    return true;
  } catch (e) { return false; }
}
if (OO_LANG !== "en") loadCachedDict(OO_LANG); // synchronous, before first paint

(function initI18n() {
  const nav = document.querySelector(".nav-inner");
  if (nav && !document.getElementById("langSel")) {
    const sel = document.createElement("select");
    sel.id = "langSel";
    sel.className = "lang-select";
    sel.setAttribute("aria-label", "Language / 语言");
    sel.innerHTML = OO_LANGS.map(([v, l]) => `<option value="${v}">${l}</option>`).join("");
    sel.value = OO_LANG;
    sel.addEventListener("change", async () => {
      OO_LANG = sel.value;
      localStorage.setItem("oo-lang", OO_LANG);
      sel.disabled = true;
      await loadLang(OO_LANG);
      sel.disabled = false;
      applyI18n();
    });
    nav.appendChild(sel);
  }
  applyI18n();
  if (!I18N[OO_LANG]) loadLang(OO_LANG).then((ok) => { if (ok) applyI18n(); });
})();
